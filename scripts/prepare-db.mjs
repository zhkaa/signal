import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const directory = new URL('../supabase/migrations/', import.meta.url);
const files = (await readdir(directory)).filter((name) => name.endsWith('.sql')).sort();
const sections = await Promise.all(
  files.map(async (name) => {
    const sql = await readFile(new URL(name, directory), 'utf8');
    return (
      '-- Source: ' +
      name +
      '\n' +
      sql
        .replace(/^begin;\s*$/gim, '')
        .replace(/^commit;\s*$/gim, '')
        .trim()
    );
  }),
);
const target = new URL('../supabase/setup.sql', import.meta.url);
await writeFile(
  target,
  '-- Generated by npm run db:prepare. For a NEW, empty Signal database only.\n-- Existing projects: apply only missing numbered migrations. No tables are dropped.\nbegin;\n\n' +
    sections.join('\n\n') +
    '\n\ncommit;\n',
);
console.log('Copy into Supabase SQL Editor: ' + fileURLToPath(target));
